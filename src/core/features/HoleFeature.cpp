const char *holeTypeName(HoleType t) {
    switch(t) {
    case HoleType::Simple: return "simple";
    case HoleType::Counterbore: return "counterbore";
    case HoleType::Countersink: return "countersink";
    }
    return "simple";
}

HoleType holeTypeFromName(const std::string &s) {
    if(s == "counterbore") return HoleType::Counterbore;
    if(s == "countersink") return HoleType::Countersink;
    return HoleType::Simple;
}

struct ProfilePt {
    double r, z;
    const char *role; // name of the face generated by the segment starting here
};

// Revolves the (r, z) half-profile around the axis through `at` along `up`
// (z > 0 is above the placement face) and names the faces by segment role.
bool makeHoleTool(const std::vector<ProfilePt> &pts, const gp_Pnt &at, const gp_Dir &up, const gp_Dir &radial,
                  const std::string &prefix, NamedShape &out) {
    BRepBuilderAPI_MakePolygon poly;
    for(const auto &p : pts) poly.Add(gp_Pnt(at.XYZ() + radial.XYZ() * p.r + up.XYZ() * p.z));
    poly.Close();
    if(!poly.IsDone()) return false;
    const TopoDS_Wire wire = poly.Wire();
    BRepBuilderAPI_MakeFace mf(wire, Standard_True);
    if(!mf.IsDone()) return false;
    BRepPrimAPI_MakeRevol revol(mf.Face(), gp_Ax1(at, up), 2.0 * M_PI);
    revol.Build();
    if(!revol.IsDone()) return false;

    TopTools_IndexedMapOfShape fmap;
    TopExp::MapShapes(revol.Shape(), TopAbs_FACE, fmap);
    std::vector<FaceLabel> labels(size_t(fmap.Extent()));
    size_t k = 0;
    for(BRepTools_WireExplorer ex(wire); ex.More() && k < pts.size(); ex.Next(), ++k) {
        for(TopTools_ListOfShape::Iterator it(revol.Generated(ex.Current())); it.More(); it.Next()) {
            const int j = fmap.FindIndex(it.Value());
            if(j > 0) labels[j - 1].name = prefix + "/" + pts[k].role;
        }
    }
    for(auto &l : labels)
        if(l.name.empty()) l.name = prefix + "/other";
    out = NamedShape(revol.Shape(), std::move(labels));
    return true;
}

